export function getCleanArea(locStr: string): string {
  if (!locStr) return '';
  return locStr.replace(/\s*[-–—]\s*\d{6}.*$/, '').trim();
}

export function getPincode(locStr: string): string | null {
  if (!locStr) return null;
  const match = locStr.match(/\b\d{6}\b/);
  return match ? match[0] : null;
}
